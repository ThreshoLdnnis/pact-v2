"""Export machine protocols and TypeScript from the Pydantic source of truth."""
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from contracts.models import ApprovalRequest, BankingCommand, CandidatePlan, ExecutionReceipt, HandoffInput, HandoffRelease, RecipientSelection, TaskPlan, TaskStep
from contracts.models import CompositionInput, FaultInput, SandboxReset
from contracts.models import ClarificationDecision, ConflictDecision, ConversationInput, ConversationResponse, InterruptInput
from pact.app import create_app

ROOT = Path(__file__).resolve().parents[1]
models = [CandidatePlan, TaskPlan, TaskStep, ApprovalRequest, ExecutionReceipt, BankingCommand, RecipientSelection, HandoffInput, HandoffRelease, CompositionInput, FaultInput, SandboxReset, ClarificationDecision, ConflictDecision, ConversationInput, ConversationResponse, InterruptInput]
definitions = {}
for model in models:
    schema = model.model_json_schema()
    definitions.update(schema.pop("$defs", {}))
    definitions[model.__name__] = schema


def ts(node):
    if "$ref" in node:
        return node["$ref"].split("/")[-1]
    if "const" in node:
        return json.dumps(node["const"], ensure_ascii=False)
    if "enum" in node:
        return " | ".join(json.dumps(x, ensure_ascii=False) for x in node["enum"])
    for union in ("anyOf", "oneOf"):
        if union in node:
            return "(" + " | ".join(ts(x) for x in node[union]) + ")"
    kind = node.get("type")
    if kind == "array":
        return f"Array<{ts(node['items'])}>"
    if kind == "object":
        if "properties" not in node:
            return "Record<string, unknown>"
        required = node.get("required", [])
        return "{ " + "; ".join(json.dumps(k) + ("" if k in required else "?") + ": " + ts(v) for k, v in node["properties"].items()) + " }"
    return {"integer": "number", "number": "number", "string": "string", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(data, encoding="utf-8")


protocol = {"$schema": "https://json-schema.org/draft/2020-12/schema", "title": "PACT Task Protocol 0.4", "$defs": definitions, "oneOf": [{"$ref": "#/$defs/" + m.__name__} for m in models]}
write(ROOT / "contracts/task-protocol.schema.json", json.dumps(protocol, ensure_ascii=False, indent=2) + "\n")
write(ROOT / "apps/workbench/src/protocol.ts", "// Generated by scripts/export_contracts.py; do not edit.\n" + "\n".join(f"export type {name} = {ts(schema)};" for name, schema in sorted(definitions.items())) + "\n")
app = create_app("sqlite:///" + (ROOT / "data/contract-export.db").as_posix(), scheduler=False)
schema = app.openapi()
write(ROOT / "contracts/openapi.json", json.dumps(schema, ensure_ascii=False, indent=2) + "\n")
banking_schema = {**schema, "paths": {p: v for p, v in schema["paths"].items() if "/banking/" in p}}
write(ROOT / "contracts/banking-tool.openapi.json", json.dumps(banking_schema, ensure_ascii=False, indent=2) + "\n")
app.state.db.engine.dispose()
print("Exported Task Protocol, Banking Tool API, complete OpenAPI and TypeScript types.")
